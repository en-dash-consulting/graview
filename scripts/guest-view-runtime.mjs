#!/usr/bin/env node
/**
 * A WORKER VIEW'S RUNTIME, AS TEXT (FR-96).
 *
 * A view written by a chat is one plain script with no imports and no
 * build, against the `graview` global. The host makes it a worker by
 * putting the runtime (`@graview/guest/worker/view`: Remote DOM's polyfill,
 * the hardening, the channel and the global) in front of it — so the host
 * needs the runtime as one classic script it can hold in memory, without
 * esbuild in the page. This bundles it into
 * `packages/guest/src/host/view-runtime.generated.ts`, which the host
 * fetches only when it first starts a view from its source.
 *
 * `packages/guest/tests/unit/a-view-needs-no-build.test.ts` builds it again
 * and fails when the file is not current.
 *
 *   node scripts/guest-view-runtime.mjs   (pnpm guest:runtime)
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const GENERATED = resolve(repoRoot, "packages/guest/src/host/view-runtime.generated.ts");

/** The runtime, bundled as the host will run it, and the module that holds it. */
export async function viewRuntimeModule(banner) {
  const require = createRequire(resolve(repoRoot, "packages/guest/package.json"));
  const { build } = require("esbuild");
  const result = await build({
    entryPoints: [resolve(repoRoot, "packages/guest/src/worker/view.ts")],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    banner: { js: banner },
    legalComments: "none",
    supported: { "dynamic-import": false },
    define: { "process.env.NODE_ENV": '"production"' },
    write: false,
    logLevel: "silent",
  });
  const script = result.outputFiles[0].text;
  return `/*
 * GENERATED by scripts/guest-view-runtime.mjs from src/worker/view.ts — do not edit.
 * A worker view's runtime as one classic script (FR-96): the host puts it in
 * front of a view's own source. Carries Remote DOM (MIT, Shopify Inc.).
 */
export const VIEW_RUNTIME: string = ${JSON.stringify(script)};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { GUEST_BUNDLE_BANNER } = await import(resolve(repoRoot, "packages/guest/dist/build.js"));
  writeFileSync(GENERATED, await viewRuntimeModule(GUEST_BUNDLE_BANNER));
  process.stdout.write(`wrote ${GENERATED}\n`);
}
